@pytest.mark.parametrize('algorithm', [algorithm for algorithm, _, _ in default_algorithms], ids=algorithm_ids)
def test_fmv_voice_renders_default_algorithm(algorithm):
    source = FMVoice(duration=0.05, algorithm=algorithm, sample_rate=8000)
    audio_data = source.get_audio_data(source.audio_format.bytes_per_second // 20)

    assert audio_data is not None
    assert audio_data.length > 0


def test_fmv_voice_evaluates_each_operator_once_per_sample():
    source = FMVoice(duration=0.01, algorithm=ALGORITHM_5, sample_rate=8000)
    calls = [0, 0, 0, 0]

    for index, op in enumerate(source.ops):
        process = op.process

        def wrapped(modulation=0.0, index=index, process=process):
            calls[index] += 1
            return process(modulation)

        op.process = wrapped

    source.get_audio_data(160)  # 80 samples.
    assert calls == [80, 80, 80, 80]


def test_fmv_voice_validates_algorithm():
    algorithm = Algorithm("No carriers")
    with pytest.raises(ValueError, match="carrier"):
        FMVoice(duration=0.1, algorithm=algorithm, sample_rate=8000)


def test_fmv_voice_set_algorithm():
    source = FMVoice(duration=0.1, algorithm=ALGORITHM_7, sample_rate=8000, feedback_level=0.5)
    source.set_algorithm(ALGORITHM_5)

    assert source.algorithm is ALGORITHM_5
    assert source._carriers == (1, 2, 3)
    assert source.ops[0].feedback == 0.5
    assert source.ops[1].feedback == 0.0
